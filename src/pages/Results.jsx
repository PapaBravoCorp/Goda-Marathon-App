import React, { useState, useEffect, useMemo } from 'react';
import { Link } from 'react-router-dom';
import { Search, Filter, Loader, Trophy, Clock } from 'lucide-react';
import { getPublishedResults } from '../utils/services/registrations';
import { getEventCategories } from '../utils/services/categories';
import { getCurrentEvent } from '../utils/services/events';
import { CURRENT_EVENT } from '../utils/constants';
import Seo from '../components/Seo';

/**
 * Race results.
 *
 * Everything this page used to show was invented. Five finishers were hardcoded
 * into the component ("David Kiprono", "Sarah Jenkins", and three more), and
 * every real registration carried a `mock_finish_time` generated by
 * Math.random() at sign-up -- so anyone who merely registered could search
 * their own bib and be shown a finishing time and a rank for a race that had
 * not happened.
 *
 * Results are a factual record. Runners cite them for club standings and
 * qualifying times. The page now reads only genuine timings, and shows nothing
 * at all until an organiser publishes them from the admin panel.
 */

const STATUS_LABELS = {
  FINISHED: 'Finished',
  DNF: 'Did not finish',
  DNS: 'Did not start',
  DQ: 'Disqualified',
};

export default function Results() {
  const [searchTerm, setSearchTerm] = useState('');
  const [categoryFilter, setCategoryFilter] = useState('');
  const [results, setResults] = useState([]);
  const [categoryOptions, setCategoryOptions] = useState([]);
  const [event, setEvent] = useState(null);
  const [isLoading, setIsLoading] = useState(true);

  useEffect(() => {
    let cancelled = false;

    (async () => {
      try {
        const ev = await getCurrentEvent();
        if (cancelled) return;
        setEvent(ev);

        const eventId = ev?.id || CURRENT_EVENT.slug;
        const [rows, cats] = await Promise.all([
          getPublishedResults(eventId),
          getEventCategories(eventId),
        ]);
        if (cancelled) return;

        setResults(rows);
        setCategoryOptions(
          cats.length > 0
            ? cats.map(c => c.name)
            : [...new Set(rows.map(r => r.category).filter(Boolean))]
        );
      } catch (error) {
        console.error('Error fetching results:', error);
      } finally {
        if (!cancelled) setIsLoading(false);
      }
    })();

    return () => { cancelled = true; };
  }, []);

  const filtered = useMemo(() => {
    const term = searchTerm.trim().toLowerCase();
    return results.filter(r => {
      const matchesSearch =
        !term ||
        (r.runner_name || '').toLowerCase().includes(term) ||
        String(r.bib || '').includes(term);
      const matchesCategory = !categoryFilter || r.category === categoryFilter;
      return matchesSearch && matchesCategory;
    });
  }, [results, searchTerm, categoryFilter]);

  const eventName = event?.name || CURRENT_EVENT.name;

  if (isLoading) {
    return (
      <div className="section" style={{ minHeight: '60vh', display: 'flex', alignItems: 'center', justifyContent: 'center' }}>
        <Loader size={32} className="spin" style={{ color: 'var(--color-primary)' }} aria-hidden="true" />
        <span className="sr-only">Loading results…</span>
      </div>
    );
  }

  // Nothing published yet. Say so plainly rather than rendering an empty table
  // that reads as "you were not in the race".
  if (results.length === 0) {
    return (
      <div className="section" style={{ minHeight: '70vh' }}>
        <Seo
          title={`Results — ${eventName}`}
          description={`Official race results for ${eventName} will be published here after the event.`}
        />
        <div className="container">
          <h1 className="text-center" style={{ marginBottom: '16px' }}>
            Race <span className="accent-text">Results</span>
          </h1>

          <div className="glass" style={{ maxWidth: '640px', margin: '40px auto', padding: '48px 32px', borderRadius: '16px', textAlign: 'center' }}>
            <Clock size={44} style={{ color: 'var(--color-primary)', marginBottom: '20px' }} aria-hidden="true" />
            <h2 style={{ fontSize: '1.5rem', marginBottom: '12px' }}>Results are not published yet</h2>
            <p className="text-muted" style={{ marginBottom: '28px' }}>
              Official timings for {eventName} go up here once every finisher has been
              verified. Follow us for the announcement.
            </p>
            <Link to="/event" className="btn btn-primary">Event details</Link>
          </div>
        </div>
      </div>
    );
  }

  return (
    <div className="section" style={{ minHeight: '80vh' }}>
      <Seo
        title={`Results — ${eventName}`}
        description={`Official finish times and rankings for ${eventName}.`}
      />
      <div className="container">
        <h1 className="text-center" style={{ marginBottom: '16px' }}>
          Race <span className="accent-text">Results</span>
        </h1>
        <p className="text-center text-muted" style={{ marginBottom: '40px', fontSize: '1.125rem' }}>
          Official times and rankings for {eventName}.
        </p>

        <div className="glass" style={{ maxWidth: '800px', margin: '0 auto 40px auto', padding: '24px', borderRadius: '16px' }}>
          <div className="results-filters">
            <div className="filter-search">
              <Search style={{ position: 'absolute', top: '14px', left: '16px', color: 'var(--color-text-muted)' }} aria-hidden="true" />
              <label htmlFor="results-search" className="sr-only">Search by bib number or name</label>
              <input
                id="results-search"
                type="search"
                placeholder="Search by Bib or Name…"
                value={searchTerm}
                onChange={(e) => setSearchTerm(e.target.value)}
                style={{ paddingLeft: '50px', borderRadius: '8px', width: '100%' }}
              />
            </div>

            <div className="filter-category">
              <Filter style={{ position: 'absolute', top: '14px', left: '16px', color: 'var(--color-text-muted)' }} aria-hidden="true" />
              <label htmlFor="results-category" className="sr-only">Filter by category</label>
              <select
                id="results-category"
                value={categoryFilter}
                onChange={(e) => setCategoryFilter(e.target.value)}
                style={{ paddingLeft: '50px', borderRadius: '8px', width: '100%', appearance: 'none', background: 'rgba(255,255,255,0.05)' }}
              >
                <option value="">All Categories</option>
                {categoryOptions.map(c => <option key={c} value={c}>{c}</option>)}
              </select>
            </div>
          </div>

          <p className="text-muted" style={{ marginTop: '16px', marginBottom: 0, fontSize: '0.85rem', textAlign: 'center' }} role="status">
            Showing {filtered.length} of {results.length} {results.length === 1 ? 'entry' : 'entries'}
          </p>
        </div>

        {/* Mobile card view */}
        <div className="results-cards">
          {filtered.map((result) => (
            <div key={result.bib} className="glass" style={{ padding: '16px 20px', borderRadius: '12px', marginBottom: '12px', borderLeft: '3px solid var(--color-primary)' }}>
              <div style={{ display: 'flex', justifyContent: 'space-between', alignItems: 'center', marginBottom: '8px' }}>
                <span style={{ fontWeight: 800, fontSize: '1.1rem' }}>
                  {result.category_rank ? `#${result.category_rank}` : '—'}
                </span>
                <span className="badge badge-primary">{result.bib}</span>
              </div>
              <div style={{ fontWeight: 700, fontSize: '1rem', marginBottom: '4px' }}>{result.runner_name}</div>
              <div style={{ display: 'flex', justifyContent: 'space-between', alignItems: 'center' }}>
                <span className="text-muted" style={{ fontSize: '0.85rem' }}>{result.category}</span>
                <span style={{ color: 'var(--color-primary)', fontWeight: 800 }}>
                  {result.finish_time || STATUS_LABELS[result.finish_status] || result.finish_status}
                </span>
              </div>
            </div>
          ))}
          {filtered.length === 0 && (
            <div style={{ padding: '40px 20px', textAlign: 'center', color: 'var(--color-text-muted)' }}>
              No results match your search.
            </div>
          )}
        </div>

        {/* Desktop table view */}
        <div className="results-table-desktop glass" style={{ borderRadius: '16px', overflow: 'hidden' }}>
          <div className="results-table-wrap">
            <table style={{ width: '100%', borderCollapse: 'collapse' }}>
              <caption className="sr-only">Official race results for {eventName}</caption>
              <thead>
                <tr style={{ background: 'rgba(255,255,255,0.05)', textAlign: 'left' }}>
                  <th scope="col" style={{ padding: '16px 20px', color: 'var(--color-text-muted)', fontWeight: 600 }}>Category Rank</th>
                  <th scope="col" style={{ padding: '16px 20px', color: 'var(--color-text-muted)', fontWeight: 600 }}>Overall</th>
                  <th scope="col" style={{ padding: '16px 20px', color: 'var(--color-text-muted)', fontWeight: 600 }}>Bib</th>
                  <th scope="col" style={{ padding: '16px 20px', color: 'var(--color-text-muted)', fontWeight: 600 }}>Name</th>
                  <th scope="col" style={{ padding: '16px 20px', color: 'var(--color-text-muted)', fontWeight: 600 }}>Category</th>
                  <th scope="col" style={{ padding: '16px 20px', color: 'var(--color-text-muted)', fontWeight: 600 }}>Time</th>
                </tr>
              </thead>
              <tbody>
                {filtered.map((result, i) => (
                  <tr key={result.bib} style={{ borderTop: '1px solid var(--color-border)', backgroundColor: i % 2 === 0 ? 'transparent' : 'rgba(255,255,255,0.02)' }}>
                    <td style={{ padding: '16px 20px', fontWeight: 800 }}>
                      {result.category_rank ? (
                        <span style={{ display: 'inline-flex', alignItems: 'center', gap: '6px' }}>
                          {result.category_rank <= 3 && <Trophy size={15} style={{ color: 'var(--color-accent)' }} aria-hidden="true" />}
                          #{result.category_rank}
                        </span>
                      ) : '—'}
                    </td>
                    <td style={{ padding: '16px 20px' }} className="text-muted">
                      {result.overall_rank ? `#${result.overall_rank}` : '—'}
                    </td>
                    <td style={{ padding: '16px 20px' }}><span className="badge badge-primary">{result.bib}</span></td>
                    <td style={{ padding: '16px 20px', fontWeight: 600 }}>{result.runner_name}</td>
                    <td style={{ padding: '16px 20px' }}>{result.category}</td>
                    <td style={{ padding: '16px 20px', color: 'var(--color-primary)', fontWeight: 800 }}>
                      {result.finish_time || (
                        <span className="text-muted" style={{ fontWeight: 600 }}>
                          {STATUS_LABELS[result.finish_status] || result.finish_status}
                        </span>
                      )}
                    </td>
                  </tr>
                ))}
              </tbody>
            </table>
          </div>
          {filtered.length === 0 && (
            <div style={{ padding: '60px 20px', textAlign: 'center', color: 'var(--color-text-muted)' }}>
              No results match your search.
            </div>
          )}
        </div>
      </div>
    </div>
  );
}
